import {
  artTokens, cutawayTokens, layoutTokens, motionTokens, stockArtTokens,
  stockCutawayTokens, stockLayoutTokens, themeTokens, typeTokens,
} from './source.ts';

type Values = Readonly<Record<string, string>>;

function pairs(entries: readonly string[], indent: string, separator: string) {
  return entries.filter((_, index) => index % 2 === 0).map((entry, index) =>
    indent + [entry, entries[index * 2 + 1]].filter(value => value !== undefined).join(separator)).join('\n');
}

function combine(groups: readonly Values[]): Values {
  const values: Record<string, string> = {};
  for (const group of groups) {
    for (const [name, value] of Object.entries(group)) {
      if (Object.hasOwn(values, name)) throw new Error(`Duplicate token --${name}`);
      values[name] = value;
    }
  }
  return values;
}

function block(selector: string, groups: readonly Values[]) {
  const entries = Object.entries(combine(groups)).map(([key, value]) => `--${key}:${value};`);
  return `${selector} {\n${pairs(entries, '  ', ' ')}\n}\n`;
}

export function renderStylesheet() {
  return '/* Generated by pnpm --filter @castle-control/tokens generate. */\n'
    + block(':root, [data-theme="paper"]', [themeTokens.paper, layoutTokens,
      artTokens, cutawayTokens, motionTokens, typeTokens])
    + block('[data-theme="stock"]', [themeTokens.stock, stockLayoutTokens,
      stockArtTokens, stockCutawayTokens, motionTokens, typeTokens]);
}

export function renderMirror() {
  const groups = {
    layout: layoutTokens, stock_layout: stockLayoutTokens,
    art: artTokens, stock_art: stockArtTokens,
    cutaway: cutawayTokens, stock_cutaway: stockCutawayTokens,
    motion: motionTokens, type: typeTokens,
  };
  const mirror = Object.entries(groups).map(([name, values]) => {
    const entries = Object.entries(values).map(([key, value]) => `${JSON.stringify(key)}: ${JSON.stringify(value)},`);
    return `  ${JSON.stringify(name)}: {\n${pairs(entries, '    ', ' ')}\n  },`;
  }).join('\n');
  const theme = JSON.stringify(themeTokens, undefined, 2).replaceAll('\n', '\n  ');
  return '// Generated; edit source.ts, then run the token generator.\n'
    + `export const tokens = {\n  theme: ${theme},\n${mirror}\n} as const;\n`
    + 'export type Theme = keyof typeof tokens.theme;\n'
    + 'export type TokenName = keyof typeof tokens.theme.paper | keyof typeof tokens.layout\n'
    + '  | keyof typeof tokens.art | keyof typeof tokens.cutaway | keyof typeof tokens.motion | keyof typeof tokens.type;\n';
}
