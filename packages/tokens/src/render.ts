import { layoutTokens, stockLayoutTokens, themeTokens } from './source.ts';

function block(selector: string, values: Readonly<Record<string, string>>) {
  return `${selector} {\n${Object.entries(values).map(([key, value]) => `  --${key}:${value};`).join('\n')}\n}\n`;
}

export function renderStylesheet() {
  return '/* Generated by pnpm --filter @castle-control/tokens generate. */\n'
    + block(':root, [data-theme="paper"]', { ...themeTokens.paper, ...layoutTokens })
    + block('[data-theme="stock"]', { ...themeTokens.stock, ...stockLayoutTokens });
}

export function renderMirror() {
  return '// Generated; edit source.ts, then run the token generator.\n'
    + `export const tokens = ${JSON.stringify({ theme: themeTokens, layout: layoutTokens, stock_layout: stockLayoutTokens }, undefined, 2)} as const;\n`
    + 'export type Theme = keyof typeof tokens.theme;\n'
    + 'export type TokenName = keyof typeof tokens.theme.paper | keyof typeof tokens.layout;\n';
}
