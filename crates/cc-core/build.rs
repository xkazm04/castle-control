//! Embeds the built-in art library (apps/desktop/public/art/library) as a
//! sorted, deterministic table of `include_bytes!` entries. Maps are not a V1
//! custom design kind and stay out of the binary. The catalog itself
//! (library.json) is parsed at runtime by `beacons::library`, its one door.
use std::{env, fs, path::Path};

const KINDS: [&str; 4] = ["beacon", "frame", "vessel", "votebar"];

fn main() {
    let manifest = env::var("CARGO_MANIFEST_DIR").expect("cargo sets the manifest dir");
    let library = Path::new(&manifest).join("../../apps/desktop/public/art/library");
    println!(
        "cargo:rerun-if-changed={}",
        library.join("library.json").display()
    );
    let mut files = Vec::new();
    for kind in KINDS {
        let dir = library.join(kind);
        println!("cargo:rerun-if-changed={}", dir.display());
        for entry in fs::read_dir(&dir).expect("library kind directory is readable") {
            let path = entry.expect("library entry is readable").path();
            let name = path
                .file_name()
                .and_then(|n| n.to_str())
                .expect("library file names are UTF-8")
                .to_owned();
            if name.ends_with(".webp") {
                files.push((format!("library/{kind}/{name}"), path));
            }
        }
    }
    files.sort();
    let mut table = String::from(
        "/// Generated by build.rs: (catalog path, bytes), sorted by path.\npub(super) static LIBRARY_FILES: &[(&str, &[u8])] = &[\n",
    );
    for (key, absolute) in files {
        let absolute = absolute.to_str().expect("library paths are UTF-8");
        table.push_str(&format!("    ({key:?}, include_bytes!({absolute:?})),\n"));
    }
    table.push_str("];\n");
    let out = Path::new(&env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("library_files.rs");
    fs::write(out, table).expect("generated library table is writable");
}
