use axum::extract::ws::{CloseFrame, Message, WebSocket};
use cc_types::{ErrorCode, ErrorEnvelope, EventKind, StreamEvent, Timestamp};
use std::collections::VecDeque;
use std::sync::Mutex;
use std::time::Duration;
use tokio::sync::watch;

struct Window {
    seq: u64,
    events: VecDeque<StreamEvent>,
}

/// The bounded history is authoritative for resume; watch carries wakeups only.
pub struct EventHub {
    capacity: usize,
    window: Mutex<Window>,
    wake: watch::Sender<u64>,
}

impl EventHub {
    pub fn new(capacity: usize) -> Result<Self, ErrorEnvelope> {
        if capacity == 0 {
            return Err(ErrorEnvelope::new(
                ErrorCode::Invalid,
                "zero event capacity",
            ));
        }
        Ok(Self {
            capacity,
            window: Mutex::new(Window {
                seq: 0,
                events: VecDeque::new(),
            }),
            wake: watch::Sender::new(0),
        })
    }

    pub fn publish(&self, kind: EventKind) -> Result<StreamEvent, ErrorEnvelope> {
        if kind == EventKind::Resync {
            return Err(ErrorEnvelope::new(
                ErrorCode::Invalid,
                "resync is generated by the transport",
            ));
        }
        let mut window = self.window.lock().map_err(|_| internal())?;
        let seq = window.seq.checked_add(1).ok_or_else(internal)?;
        let event = StreamEvent {
            seq,
            at: Timestamp::now(),
            kind,
        };
        window.seq = seq;
        window.events.push_back(event.clone());
        if window.events.len() > self.capacity {
            window.events.pop_front();
        }
        self.wake.send_replace(seq);
        Ok(event)
    }

    pub fn since(&self, since_seq: u64) -> Result<Vec<StreamEvent>, ErrorEnvelope> {
        let window = self.window.lock().map_err(|_| internal())?;
        Ok(Self::read(&window, since_seq))
    }

    fn read(window: &Window, since_seq: u64) -> Vec<StreamEvent> {
        if since_seq > window.seq || window.events.front().is_some_and(|e| since_seq < e.seq - 1) {
            return vec![StreamEvent {
                seq: window.seq,
                at: Timestamp::now(),
                kind: EventKind::Resync,
            }];
        }
        window
            .events
            .iter()
            .filter(|e| e.seq > since_seq)
            .cloned()
            .collect()
    }

    pub(crate) async fn session(
        &self,
        mut socket: WebSocket,
        since_seq: Option<u64>,
        mut shutdown: watch::Receiver<bool>,
    ) {
        // Subscribe before taking the snapshot: publishes cannot land in an attach gap.
        let mut wake = self.wake.subscribe();
        let mut cursor = since_seq.unwrap_or_else(|| *wake.borrow_and_update());
        loop {
            if *shutdown.borrow() {
                break;
            }
            let Ok(batch) = self.since(cursor) else {
                break;
            };
            for event in batch {
                let Ok(text) = serde_json::to_string(&event) else {
                    return;
                };
                if !matches!(
                    tokio::time::timeout(
                        Duration::from_secs(5),
                        socket.send(Message::Text(text.into()))
                    )
                    .await,
                    Ok(Ok(()))
                ) {
                    return;
                }
                cursor = event.seq;
            }
            tokio::select! {
                changed = wake.changed() => { if changed.is_err() { break; } }
                _ = shutdown.changed() => { break; }
                frame = socket.recv() => {
                    match frame {
                        Some(Ok(Message::Ping(data))) => {
                            if socket.send(Message::Pong(data)).await.is_err() { break; }
                        }
                        Some(Ok(Message::Pong(_))) => {}
                        _ => break,
                    }
                }
            }
        }
        let _ = socket
            .send(Message::Close(Some(CloseFrame {
                code: 1001,
                reason: "session ended".into(),
            })))
            .await;
    }
}

fn internal() -> ErrorEnvelope {
    ErrorEnvelope::new(ErrorCode::Internal, "event window unavailable")
}
